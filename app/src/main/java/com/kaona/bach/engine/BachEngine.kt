package com.kaona.bach.engine

import java.util.Random

/**
 * Core parameters shared across all Compositional Languages.
 * Maps to the 8 encoders on the hardware module.
 */
data class BachParams(
    val material: Float = 0.5f,      // 0.0-1.0: Vocabulary/seed selection
    val memory: Float = 0.5f,        // 0.0-1.0: Persistence/renewal rate
    val growth: Float = 0.5f,        // 0.0-1.0: Structural complexity/length
    val morph: Float = 0.5f,         // 0.0-1.0: Transformations (inversion, retrograde, etc.)
    val density: Float = 0.5f,       // 0.0-1.0: Number of active events
    val tension: Float = 0.5f,       // 0.0-1.0: Harmonic departure from stable state
    val interaction: Float = 0.5f,   // 0.0-1.0: Inter-voice relationships
    val humanize: Float = 0.0f       // 0.0-1.0: Micro-variations and imperfections
)

/**
 * Represents a single musical event generated by the engine.
 */
data class NoteEvent(
    val track: Int,              // 0-3 (4 voices)
    val midiNote: Int,           // 0-127
    val velocity: Int,           // 0-127
    val durationTicks: Int,      // Duration in ticks
    val startTick: Long,         // Absolute start position
    val modValue: Int = 64       // Mod output 0-127 (mapped from 0-5V)
)

/**
 * Break effect characters matching the hardware module
 */
enum class BreakCharacter(val displayName: String) {
    AUTO("Auto"),
    SILENCE("Silence"),
    AGITATION("Agitation"),
    SUSPENSION("Suspension"),
    FRAGMENT("Fragment"),
    PULSE("Pulse"),
    EROSION("Erosion"),
    EXPANSION("Expansion")
}

/**
 * The 12 Compositional Languages available in B.A.C.H.
 */
enum class CompositionalLanguage(val displayName: String) {
    FUGUE("Fugue"),
    CANON("Canon"),
    PROBA("Proba"),
    TINTINNABULI("Tintinnabuli"),
    MINIMAL("Minimal"),
    CELLULAR("Cellular"),
    TREE("Tree"),
    FRACTAL("Fractal"),
    MOTIF("Motif"),
    HYBRID("Hybrid"),
    GROOVE("Groove"),
    GROOVE_MIX("Groove Mix")
}

/**
 * Configuration for Break effects
 */
data class BreakConfig(
    val character: BreakCharacter = BreakCharacter.AUTO,
    val bars: Int = 2,      // 1, 2, 4, or 8 bars; 0 = LIVE mode
    val isLive: Boolean = false
)

/**
 * State of the generative engine
 */
data class EngineState(
    val isPlaying: Boolean = false,
    val bpm: Int = 120,
    val currentTick: Long = 0,
    val currentBar: Int = 0,
    val currentBeat: Int = 0,
    val language: CompositionalLanguage = CompositionalLanguage.FUGUE,
    val params: BachParams = BachParams(),
    val rootNote: NoteName = NoteName.C,
    val scale: Scale = Scale.MAJOR,
    val sequence: HarmonicSequence = HarmonicSequence(),   // Progressão harmônica (SEQUENCE)
    val ornaments: Float = 0f,                              // 0.0-1.0: quantidade de ornamentos (OFF-100%)
    val music: MusicSettings = MusicSettings(),             // Página MUSIC (duração, velocity, métrica, swing, frase, raiz)
    val groovePartner: CompositionalLanguage = CompositionalLanguage.CANON, // Parceiro melódico do GROOVE MIX
    val sequenceOrigin: Long = 0L,                          // Tick em que a leitura da SEQUENCE recomeçou
    val breakConfig: BreakConfig = BreakConfig(),
    val isBreakActive: Boolean = false,
    val midiChannels: IntArray = intArrayOf(1, 2, 3, 4), // MIDI channels for 4 voices
    val trackMutes: BooleanArray = booleanArrayOf(false, false, false, false),
    val presetIndex: Int = 0
)

/**
 * Main B.A.C.H. Engine - coordinates all compositional languages and manages
 * the generative composition pipeline.
 */
class BachEngine {
    private val random = Random()
    private val harmony = HarmonyProcessor()
    private val ornamentProcessor = OrnamentProcessor(random)
    private val humanizer = HumanizeProcessor(random)
    private val partnerPitch = IntArray(4) { -1 }
    @Volatile
    private var state = EngineState()
    private val eventBuffer = mutableListOf<NoteEvent>()
    private var activeNotes = Array(4) { mutableListOf<NoteEvent>() }
    private var lastGeneratedNotes = IntArray(4) { 60 } // Last note per track

    // Compositional language engines
    private val fugueEngine = FugueEngine()
    private val canonEngine = CanonEngine()
    private val probaEngine = ProbaEngine()
    private val tintinnabuliEngine = TintinnabuliEngine()
    private val minimalEngine = MinimalEngine()
    private val cellularEngine = CellularEngine()
    private val treeEngine = TreeEngine()
    private val fractalEngine = FractalEngine()
    private val motifEngine = MotifEngine()
    private val grooveEngine = GrooveEngine()

    // Ordem dos materiais do HYBRID: FUGUE, CANON, PROBA, TINTINA, MINIMAL, CELLULAR, TREE, FRACTAL, MOTIF
    private val hybridEngines: List<CompositionEngine> = listOf(
        fugueEngine, canonEngine, probaEngine, tintinnabuliEngine, minimalEngine,
        cellularEngine, treeEngine, fractalEngine, motifEngine
    )

    // Break engine
    private var breakStartTick: Long = 0
    private var breakEvents = mutableListOf<NoteEvent>()

    // Parâmetros dos 8 knobs: entram sem trava. A interface nunca espera o clock; o valor vale a partir
    // do próximo tick (menos de 6 ms depois) e getState() já o enxerga.
    private val pendingParams = java.util.concurrent.ConcurrentHashMap<String, Float>()

    fun getState(): EngineState {
        val s = state
        return if (pendingParams.isEmpty()) s else s.copy(params = withPending(s.params, false))
    }

    @Synchronized
    fun setOrnaments(amount: Float) {
        state = state.copy(ornaments = amount.coerceIn(0f, 1f))
    }

    @Synchronized
    fun setSequence(sequence: HarmonicSequence, restart: Boolean = false) {
        state = state.copy(
            sequence = sequence,
            sequenceOrigin = if (restart) state.currentTick else state.sequenceOrigin
        )
        harmony.invalidate()
    }

    @Synchronized
    fun setMusic(music: MusicSettings) {
        state = state.copy(music = music)
    }

    @Synchronized
    fun setGroovePartner(language: CompositionalLanguage) {
        state = state.copy(groovePartner = language)
        partnerPitch.fill(-1)
    }

    /** Acorde que toca em [tick] (para a tela HARMONY); null se a SEQUENCE estiver inativa. */
    fun chordDisplayAt(tick: Long): ChordDisplay? {
        val st = state
        if (!st.sequence.isActive) return null
        val pos = HarmonyEngine.locate(st.sequence, tick - st.sequenceOrigin, st.music.meter) ?: return null
        return ChordDisplay(pos.index, HarmonyEngine.label(st.sequence.steps[pos.index], st.rootNote, st.scale))
    }

    @Synchronized
    fun setState(newState: EngineState) {
        pendingParams.clear()
        harmony.invalidate()
        // Carregar um preset troca os ajustes, mas não o transporte: continua tocando/pausado onde estava
        state = newState.copy(
            isPlaying = state.isPlaying,
            currentTick = state.currentTick,
            currentBar = state.currentBar,
            currentBeat = state.currentBeat,
            trackMutes = state.trackMutes,
            sequenceOrigin = state.currentTick
        )
    }

    fun updateParam(param: String, value: Float) {
        when (param) {
            "material", "memory", "growth", "morph", "density", "tension", "interaction", "humanize" ->
                pendingParams[param] = value
        }
    }

    private fun withPending(base: BachParams, consume: Boolean): BachParams {
        if (pendingParams.isEmpty()) return base
        var p = base
        for ((key, v) in pendingParams) {
            p = when (key) {
                "material" -> p.copy(material = v)
                "memory" -> p.copy(memory = v)
                "growth" -> p.copy(growth = v)
                "morph" -> p.copy(morph = v)
                "density" -> p.copy(density = v)
                "tension" -> p.copy(tension = v)
                "interaction" -> p.copy(interaction = v)
                "humanize" -> p.copy(humanize = v)
                else -> p
            }
            if (consume) pendingParams.remove(key, v)
        }
        return p
    }

    @Synchronized
    fun setLanguage(language: CompositionalLanguage) {
        state = state.copy(language = language)
        resetLanguageState()
    }

    @Synchronized
    fun setBpm(bpm: Int) {
        state = state.copy(bpm = bpm.coerceIn(30, 300))
    }

    @Synchronized
    fun setScale(scale: Scale) {
        state = state.copy(scale = scale)
    }

    @Synchronized
    fun setRoot(root: NoteName) {
        state = state.copy(rootNote = root)
    }

    @Synchronized
    fun setMidiChannel(track: Int, channel: Int) {
        if (track in 0..3 && channel in 1..16) {
            val channels = state.midiChannels.copyOf()
            channels[track] = channel
            state = state.copy(midiChannels = channels)
        }
    }

    @Synchronized
    fun toggleTrackMute(track: Int) {
        if (track in 0..3) {
            val mutes = state.trackMutes.copyOf()
            mutes[track] = !mutes[track]
            state = state.copy(trackMutes = mutes)
        }
    }

    @Synchronized
    fun play() {
        if (state.isPlaying) return
        // O STOP é uma pausa: tocar de novo retoma do mesmo ponto. Só um início "limpo" zera a forma.
        val fresh = state.currentTick == 0L
        state = state.copy(isPlaying = true)
        if (fresh) {
            state = state.copy(currentBar = 0, currentBeat = 0, sequenceOrigin = 0L)
            harmony.reset()
            humanizer.reset()
            ornamentProcessor.clear()
            resetLanguageState()
        }
    }

    @Synchronized
    fun stop() {
        state = state.copy(isPlaying = false)
        ornamentProcessor.clear()
        eventBuffer.clear()
        activeNotes.forEach { it.clear() }
    }

    @Synchronized
    fun reset() {
        val wasPlaying = state.isPlaying
        stop()
        state = state.copy(currentTick = 0, currentBar = 0, currentBeat = 0, sequenceOrigin = 0L)
        lastGeneratedNotes = IntArray(4) { 60 }
        harmony.reset()
        humanizer.reset()
        resetLanguageState()
        if (wasPlaying) play()
    }

    @Synchronized
    fun triggerBreak() {
        state = state.copy(isBreakActive = true)
        breakStartTick = state.currentTick
        breakEvents = generateBreakEvents()
    }

    @Synchronized
    fun releaseBreak() {
        state = state.copy(isBreakActive = false)
        breakEvents.clear()
    }

    @Synchronized
    fun setBreakConfig(config: BreakConfig) {
        state = state.copy(breakConfig = config)
    }

    /**
     * Called on each clock tick to generate new events.
     * Returns list of NoteEvents to be sent as MIDI.
     */
    @Synchronized
    fun processTick(): List<NoteEvent> {
        if (!state.isPlaying) return emptyList()

        // Parâmetros dos knobs recebidos desde o último tick
        if (pendingParams.isNotEmpty()) {
            state = state.copy(params = withPending(state.params, true))
        }

        val currentTick = state.currentTick
        val meter = state.music.meter
        val ticksPerBar = meter.barTicks
        val newBeat = ((currentTick % ticksPerBar) / meter.beatTicks).toInt()
        val newBar = (currentTick / ticksPerBar).toInt()

        state = state.copy(
            currentTick = currentTick + 1,
            currentBeat = newBeat,
            currentBar = newBar
        )

        // PHRASE: no fim da frase o contador volta a zero e as linguagens reiniciam a arquitetura.
        // A SEQUENCE não é afetada. INFINITE (0) nunca reinicia.
        val phraseBars = state.music.phraseBars
        if (phraseBars > 0 && currentTick > 0 &&
            currentTick % (phraseBars.toLong() * ticksPerBar) == 0L
        ) {
            resetLanguageState()
        }

        // Check if break should end
        if (state.isBreakActive && !state.breakConfig.isLive) {
            val breakDurationTicks = state.breakConfig.bars * ticksPerBar
            if (currentTick - breakStartTick >= breakDurationTicks) {
                releaseBreak()
            }
        }

        // Generate events at appropriate intervals
        val events = mutableListOf<NoteEvent>()

        if (state.isBreakActive) {
            events.addAll(getBreakEventsAtTick(currentTick))
        } else {
            events.addAll(generateEventsAtTick(currentTick))
        }

        // Pipeline musical: mute -> raiz (oitava) -> harmonia -> humanize (gesto) -> duração
        //                   -> ornamentos -> swing -> velocity
        val audible = events.filter { !state.trackMutes[it.track] }
        val transposed = MusicShaper.transpose(audible, state)
        val harmonized = harmony.apply(transposed, currentTick, state)
        val humanized = humanizer.process(harmonized, currentTick, state) { e, d ->
            ornamentProcessor.defer(e, currentTick, d)
        }
        val durationed = MusicShaper.applyDuration(humanized, currentTick, state)
        val ornamented = ornamentProcessor.process(durationed, currentTick, state)

        // SWING: a contratempo sai um pouco depois; o tempo seguinte continua no relógio
        // Os Materials do GROOVE escritos em tercinas não são deformados uma segunda vez
        val nativelyTernary = (state.language == CompositionalLanguage.GROOVE ||
            state.language == CompositionalLanguage.GROOVE_MIX) && grooveEngine.isTernary(state.params.material)
        val swingDelay = if (nativelyTernary) 0 else MusicShaper.swingDelay(currentTick, state)
        val onTime: List<NoteEvent> = if (swingDelay > 0 && ornamented.isNotEmpty()) {
            for (e in ornamented) ornamentProcessor.defer(e, currentTick, swingDelay)
            emptyList()
        } else {
            ornamented
        }

        // Notas agendadas (ornamentos, swing, microtiming) que vencem neste tick
        val due = ornamentProcessor.takeDue(currentTick).filter { !state.trackMutes[it.track] }
        val combined = if (due.isEmpty()) onTime else onTime + due
        val finalEvents = MusicShaper.applyVelocity(combined, currentTick, state)

        // Apply humanization
        if (state.params.humanize > 0f) {
            return finalEvents.map { event ->
                event.copy(
                    velocity = RhythmUtils.humanizeVelocity(event.velocity, state.params.humanize, random),
                    modValue = RhythmUtils.humanizeVelocity(event.modValue, state.params.humanize * 0.5f, random)
                )
            }
        }

        return finalEvents
    }

    private fun generateEventsAtTick(tick: Long): List<NoteEvent> {
        return when (state.language) {
            CompositionalLanguage.FUGUE -> fugueEngine.generate(tick, state, random)
            CompositionalLanguage.CANON -> canonEngine.generate(tick, state, random)
            CompositionalLanguage.PROBA -> probaEngine.generate(tick, state, random)
            CompositionalLanguage.TINTINNABULI -> tintinnabuliEngine.generate(tick, state, random)
            CompositionalLanguage.MINIMAL -> minimalEngine.generate(tick, state, random)
            CompositionalLanguage.CELLULAR -> cellularEngine.generate(tick, state, random)
            CompositionalLanguage.TREE -> treeEngine.generate(tick, state, random)
            CompositionalLanguage.FRACTAL -> fractalEngine.generate(tick, state, random)
            CompositionalLanguage.MOTIF -> motifEngine.generate(tick, state, random)
            CompositionalLanguage.HYBRID -> generateHybrid(tick)
            CompositionalLanguage.GROOVE -> grooveEngine.generate(tick, state, random)
            CompositionalLanguage.GROOVE_MIX -> generateGrooveMix(tick)
        }
    }

    /**
     * HYBRID: MATERIAL escolhe a linguagem de referência entre as nove.
     * INTERACTION distribui: acima de 66% as 4 vozes seguem a linguagem de referência; entre 33 e 66%
     * duas linguagens dividem as vozes em pares; abaixo disso cada voz recebe a sua.
     * MORPH acima de 66% gira a atribuição um passo a cada meio compasso.
     */
    private fun generateHybrid(tick: Long): List<NoteEvent> {
        val engines = hybridEngines
        val ref = MaterialCatalog.index(CompositionalLanguage.HYBRID, state.params.material)
            .coerceIn(0, engines.size - 1)
        val interaction = state.params.interaction

        val assignment = IntArray(4)
        when {
            interaction > 0.66f -> for (t in 0..3) assignment[t] = ref
            interaction > 0.33f -> {
                val partner = (ref + 1) % engines.size
                assignment[0] = ref
                assignment[1] = ref
                assignment[2] = partner
                assignment[3] = partner
            }
            else -> for (t in 0..3) assignment[t] = (ref + t) % engines.size
        }

        if (state.params.morph > 0.66f) {
            val halfBar = (state.music.meter.barTicks / 2).coerceAtLeast(1)
            val rot = ((tick / halfBar) % 4).toInt()
            if (rot != 0) {
                val copy = assignment.copyOf()
                for (t in 0..3) assignment[t] = copy[(t + rot) % 4]
            }
        }

        val events = ArrayList<NoteEvent>()
        for (idx in assignment.distinct()) {
            val generated = engines[idx].generate(tick, state, random)
            for (e in generated) {
                if (e.track in 0..3 && assignment[e.track] == idx) events.add(e)
            }
        }
        return events
    }

    /** GROOVE MIX: o ritmo vem do GROOVE e as alturas, do parceiro escolhido. */
    private fun generateGrooveMix(tick: Long): List<NoteEvent> {
        val partnerEvents = when (state.groovePartner) {
            CompositionalLanguage.PROBA -> probaEngine.generate(tick, state, random)
            CompositionalLanguage.CELLULAR -> cellularEngine.generate(tick, state, random)
            CompositionalLanguage.TREE -> treeEngine.generate(tick, state, random)
            CompositionalLanguage.FRACTAL -> fractalEngine.generate(tick, state, random)
            CompositionalLanguage.MOTIF -> motifEngine.generate(tick, state, random)
            CompositionalLanguage.HYBRID -> generateHybrid(tick)
            else -> canonEngine.generate(tick, state, random)
        }
        for (e in partnerEvents) {
            if (e.track in 0..3) partnerPitch[e.track] = e.midiNote
        }

        return grooveEngine.generateMix(tick, state, random).map { e ->
            val p = if (e.track in 0..3) partnerPitch[e.track] else -1
            if (p >= 0) e.copy(midiNote = p) else e
        }
    }

    private fun generateBreakEvents(): MutableList<NoteEvent> {
        val events = mutableListOf<NoteEvent>()
        val ticksPerBar = RhythmUtils.QUARTER * 4
        val breakDuration = if (state.breakConfig.isLive) ticksPerBar * 4 else state.breakConfig.bars * ticksPerBar

        when (state.breakConfig.character) {
            BreakCharacter.SILENCE -> { /* No events */ }
            BreakCharacter.AGITATION -> {
                // Rapid, dense rhythmic activity
                for (tick in 0L until breakDuration.toLong() step RhythmUtils.SIXTEENTH.toLong()) {
                    for (track in 0..3) {
                        if (random.nextFloat() < 0.7f) {
                            val note = lastGeneratedNotes[track] + random.nextInt(13) - 6
                            events.add(NoteEvent(track, note.coerceIn(24, 108), random.nextInt(40) + 87, RhythmUtils.SIXTEENTH, breakStartTick + tick))
                        }
                    }
                }
            }
            BreakCharacter.SUSPENSION -> {
                // Hold current notes as long sustained tones
                for (track in 0..3) {
                    events.add(NoteEvent(track, lastGeneratedNotes[track], 80, breakDuration, breakStartTick))
                }
            }
            BreakCharacter.FRAGMENT -> {
                // Short fragmented bursts
                for (tick in 0L until breakDuration.toLong() step RhythmUtils.EIGHTH.toLong()) {
                    val track = random.nextInt(4)
                    if (random.nextFloat() < 0.4f) {
                        events.add(NoteEvent(track, lastGeneratedNotes[track], random.nextInt(60) + 40, RhythmUtils.SIXTEENTH, breakStartTick + tick))
                    }
                }
            }
            BreakCharacter.PULSE -> {
                // Regular rhythmic pulse on all voices
                for (tick in 0L until breakDuration.toLong() step RhythmUtils.QUARTER.toLong()) {
                    for (track in 0..3) {
                        events.add(NoteEvent(track, lastGeneratedNotes[track], 100, RhythmUtils.EIGHTH, breakStartTick + tick))
                    }
                }
            }
            BreakCharacter.EROSION -> {
                // Gradually thinning out
                var prob = 0.8f
                for (tick in 0L until breakDuration.toLong() step RhythmUtils.EIGHTH.toLong()) {
                    for (track in 0..3) {
                        if (random.nextFloat() < prob) {
                            events.add(NoteEvent(track, lastGeneratedNotes[track], (100 * prob).toInt(), RhythmUtils.EIGHTH, breakStartTick + tick))
                        }
                    }
                    prob *= 0.92f
                }
            }
            BreakCharacter.EXPANSION -> {
                // Growing outward in register and density
                var spread = 0
                for (tick in 0L until breakDuration.toLong() step RhythmUtils.EIGHTH.toLong()) {
                    for (track in 0..3) {
                        val note = lastGeneratedNotes[track] + (if (track % 2 == 0) spread else -spread)
                        events.add(NoteEvent(track, note.coerceIn(24, 108), 80 + spread, RhythmUtils.QUARTER, breakStartTick + tick))
                    }
                    spread += 1
                }
            }
            BreakCharacter.AUTO -> {
                // Automatically choose based on tension
                val autoChar = when {
                    state.params.tension < 0.2f -> BreakCharacter.SILENCE
                    state.params.tension < 0.4f -> BreakCharacter.SUSPENSION
                    state.params.tension < 0.6f -> BreakCharacter.FRAGMENT
                    state.params.tension < 0.8f -> BreakCharacter.AGITATION
                    else -> BreakCharacter.EXPANSION
                }
                val tempConfig = state.breakConfig.copy(character = autoChar)
                state = state.copy(breakConfig = tempConfig)
                return generateBreakEvents()
            }
        }
        return events
    }

    private fun getBreakEventsAtTick(tick: Long): List<NoteEvent> {
        return breakEvents.filter { it.startTick == tick }
    }

    private fun resetLanguageState() {
        fugueEngine.reset()
        canonEngine.reset()
        probaEngine.reset()
        tintinnabuliEngine.reset()
        minimalEngine.reset()
        cellularEngine.reset()
        treeEngine.reset()
        fractalEngine.reset()
        motifEngine.reset()
        grooveEngine.reset()
        partnerPitch.fill(-1)
    }
}
